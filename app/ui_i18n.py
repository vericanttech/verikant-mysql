def current_ui_language() -> str:
    language = (request.cookies.get("vericant_language") or "fr").lower()
    return language if language in SUPPORTED_LANGUAGES else "fr"


def translate_ui(text: str, language: str | None = None) -> str:
    language = language or current_ui_language()
    return ENGLISH.get(text, text) if language == "en" else text
